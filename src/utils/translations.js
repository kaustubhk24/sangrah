const fallbackLang = (code) => {
  if (translations[code]) return code;
  if (['sa', 'gu', 'kn', 'te', 'ta', 'ml', 'bn'].includes(code)) return 'hi';
  return 'mr';
};

export const LanguageContext = createContext();

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState('mr');

  useEffect(() => {
    if (typeof window === 'undefined') return;
    const stored = window.localStorage.getItem('site-language') || 'mr';
    setLang(stored);
  }, []);

  const changeLanguage = (newLang) => {
    setLang(newLang);
    if (typeof window !== 'undefined') {
      window.localStorage.setItem('site-language', newLang);
    }
  };

  const t = (key) => {
    const activeLang = fallbackLang(lang);
    return translations[activeLang][key] || translations['mr'][key] || key;
  };

  const translateNumbers = (value) => {
    if (value === undefined || value === null) return '';
    const numStr = value.toString();
    if (lang !== 'mr' && lang !== 'hi') return numStr;
    const devanagariDigits = ['०', '१', '२', '३', '४', '५', '६', '७', '८', '९'];
    return numStr.replace(/[0-9]/g, (digit) => devanagariDigits[parseInt(digit, 10)]);
  };

  return (
    <LanguageContext.Provider value={{ lang, changeLanguage, t, translateNumbers }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useTranslation() {
  return useContext(LanguageContext);
}
